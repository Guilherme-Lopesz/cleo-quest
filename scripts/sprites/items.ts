const OUT = join(process.cwd(), 'public', 'pixel-art', 'items');
mkdirSync(OUT, { recursive: true });
for (const [name, rows] of Object.entries(ICONS)) {
  const c = new PixelCanvas(16, 16);
  c.stamp(0, 0, rows, C);
  writeFileSync(join(OUT, `${name}.png`), c.toPNG());
}
// prancha para inspeção
const names = Object.keys(ICONS);
const sheet = new PixelCanvas(16 * names.length, 16);
names.forEach((n, i) => {
  const c = new PixelCanvas(16, 16);
  c.stamp(0, 0, ICONS[n]!, C);
  sheet.blit(c, i * 16, 0);
});
if (process.argv.includes('--preview'))
  writeFileSync(join(process.cwd(), 'preview-items.png'), sheet.scaled(6).toPNG());
console.info(`itens: ${names.length} ícones → ${OUT}`);
